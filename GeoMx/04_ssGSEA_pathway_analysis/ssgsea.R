#
#   1. Preprocessed GeoMx object generated by:
#        01_preprocessing_QC_normalization.R
#
#      default:
#        results/GeoMx/01_preprocessing_QC_normalization/
#          GeoMx_preprocessed_Q3_normalized.rds
#
#   2. Preserved ROI-level ssGSEA score matrix:
#        data/GeoMx/ssGSEA/ssgsea_results.csv
#
#      Rows    = pathways
#      Columns = GeoMx ROI/sample IDs
#
# Output:
#      results/GeoMx/03_ssGSEA_pathway_analysis/
#
###############################################################################


