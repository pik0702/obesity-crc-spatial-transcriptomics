clean_sample_id <- function(x) {
  
  x <- basename(
    as.character(x)
  )
  
  # remove .dcc extension
  x <- sub(
    "\\.dcc$",
    "",
    x,
    ignore.case = TRUE
  )
  
  # convert "-" to "."
  x <- gsub(
    "-",
    ".",
    x,
    fixed = TRUE
  )
  
  x
}


standardize_class <- function(x) {
  
  x <- trimws(
    as.character(x)
  )
  
  dplyr::case_when(
    tolower(x) == "normal" ~ "Normal",
    tolower(x) == "tumor"  ~ "Tumor",
    tolower(x) == "tumour" ~ "Tumor",
    TRUE ~ x
  )
}


standardize_obesity <- function(x) {
  
  x <- trimws(
    as.character(x)
  )
  
  low <- tolower(x)
  
  dplyr::case_when(
    low %in% c(
      "normal",
      "non-obese",
      "nonobese",
      "non obese",
      "non_obese"
    ) ~ "Normal",
    
    low == "obese" ~ "Obese",
    
    TRUE ~ x
  )
}


standardize_roi <- function(x) {
  
  x <- trimws(
    as.character(x)
  )
  
  dplyr::case_when(
    tolower(x) %in% c(
      "cd3",
      "immune",
      "immune cell"
    ) ~ "CD3",
    
    tolower(x) %in% c(
      "epithelial",
      "epithelium"
    ) ~ "Epithelial",
    
    tolower(x) %in% c(
      "adipose",
      "adipose tissue"
    ) ~ "Adipose",
    
    TRUE ~ x
  )
}


safe_row_zscore <- function(x) {
  
  s <- stats::sd(
    x,
    na.rm = TRUE
  )
  
  m <- mean(
    x,
    na.rm = TRUE
  )
  
  if (
    !is.finite(s) ||
    s == 0
  ) {
    return(
      rep(
        0,
        length(x)
      )
    )
  }
  
  (x - m) / s
}


safe_wilcox <- function(values, group) {
  
  ok <- (
    is.finite(values) &
      !is.na(group)
  )
  
  values <- values[ok]
  group <- droplevels(
    factor(group[ok])
  )
  
  if (
    length(values) == 0 ||
    nlevels(group) != 2
  ) {
    return(NA_real_)
  }
  
  tryCatch(
    stats::wilcox.test(
      values ~ group
    )$p.value,
    error = function(e) NA_real_
  )
}


