###############################################################################
# 7. Figure 1F heatmaps
###############################################################################

scaled_matrices <- list()

for (group_name in names(pathway_groups)) {
  
  selected_pathways <- pathway_groups[[group_name]]
  
  missing_pathways <- setdiff(
    selected_pathways,
    rownames(group_means)
  )
  
  if (length(missing_pathways) > 0) {
    warning(
      "[",
      group_name,
      "] pathway(s) not found and omitted: ",
      paste(
        missing_pathways,
        collapse = ", "
      )
    )
  }
  
  selected_pathways <- intersect(
    selected_pathways,
    rownames(group_means)
  )
  
  if (length(selected_pathways) == 0) {
    warning(
      "[",
      group_name,
      "] no requested pathways were found; heatmap skipped."
    )
    next
  }
  
  # Preserve the explicit pathway order defined above.
  selected_pathways <- pathway_groups[[group_name]][
    pathway_groups[[group_name]] %in%
      selected_pathways
  ]
  
  selected_data <- group_means[
    selected_pathways,
    expected_groups,
    drop = FALSE
  ]
  
  selected_data_scaled <- matrix(
    NA_real_,
    nrow = nrow(selected_data),
    ncol = ncol(selected_data),
    dimnames = dimnames(selected_data)
  )
  
  # Original Figure 1F logic:
  # scale each pathway separately within each ROI type
  # across NO-, NO+, TO-, TO+.
  for (roi_name in names(roi_blocks)) {
    
    cols <- roi_blocks[[roi_name]]
    
    selected_data_scaled[
      ,
      cols
    ] <- t(
      apply(
        selected_data[
          ,
          cols,
          drop = FALSE
        ],
        1,
        safe_row_zscore
      )
    )
  }
  
  scaled_matrices[[group_name]] <- selected_data_scaled
  
  write.csv(
    data.frame(
      Pathway = rownames(selected_data_scaled),
      selected_data_scaled,
      check.names = FALSE
    ),
    file.path(
      OUTPUT_DIR,
      paste0(
        "Figure1F_",
        group_name,
        "_scaled_scores.csv"
      )
    ),
    row.names = FALSE
  )
  
  # A display copy with duplicated NO-/NO+/TO-/TO+ labels.
  heatmap_display <- selected_data_scaled
  
  colnames(
    heatmap_display
  ) <- rep(
    column_display_labels,
    times = 3
  )
  
  roi_split <- factor(
    rep(
      c(
        "Adipose ROI",
        "Immune ROI",
        "Epithelial ROI"
      ),
      each = 4
    ),
    levels = c(
      "Adipose ROI",
      "Immune ROI",
      "Epithelial ROI"
    )
  )
  
  ht <- ComplexHeatmap::Heatmap(
    heatmap_display,
    name = "ssGSEA\nscore",
    column_split = roi_split,
    column_gap = grid::unit(
      2.5,
      "mm"
    ),
    cluster_rows = FALSE,
    cluster_columns = FALSE,
    col = heatmap_colors,
    show_row_names = TRUE,
    show_column_names = TRUE,
    column_names_rot = 0,
    row_names_gp = grid::gpar(
      fontsize = 10
    ),
    column_names_gp = grid::gpar(
      fontsize = 9
    ),
    column_title_gp = grid::gpar(
      fontsize = 11,
      fontface = "bold"
    ),
    heatmap_legend_param = list(
      title = "ssGSEA\nscore",
      legend_height = grid::unit(
        28,
        "mm"
      )
    ),
    cell_fun = function(
    j,
    i,
    x,
    y,
    width,
    height,
    fill
    ) {
      grid::grid.rect(
        x = x,
        y = y,
        width = width,
        height = height,
        gp = grid::gpar(
          fill = fill,
          col = "black",
          lwd = 0.7
        )
      )
    }
  )
  
  # PDF
  grDevices::pdf(
    file.path(
      OUTPUT_DIR,
      paste0(
        "Figure1F_",
        group_name,
        ".pdf"
      )
    ),
    width = 8.0,
    height = max(
      3.0,
      0.45 * nrow(heatmap_display) + 2.0
    )
  )
  
  ComplexHeatmap::draw(
    ht,
    heatmap_legend_side = "right"
  )
  
  grid::grid.text(
    display_titles[[group_name]],
    x = 0.5,
    y = 0.985,
    just = c(
      "center",
      "top"
    ),
    gp = grid::gpar(
      fontsize = 14,
      fontface = "bold"
    )
  )
  
  grDevices::dev.off()
  
  # PNG
  grDevices::png(
    file.path(
      OUTPUT_DIR,
      paste0(
        "Figure1F_",
        group_name,
        ".png"
      )
    ),
    width = 8.0,
    height = max(
      3.0,
      0.45 * nrow(heatmap_display) + 2.0
    ),
    units = "in",
    res = 600
  )
  
  ComplexHeatmap::draw(
    ht,
    heatmap_legend_side = "right"
  )
  
  grid::grid.text(
    display_titles[[group_name]],
    x = 0.5,
    y = 0.985,
    just = c(
      "center",
      "top"
    ),
    gp = grid::gpar(
      fontsize = 14,
      fontface = "bold"
    )
  )
  
  grDevices::dev.off()
}


