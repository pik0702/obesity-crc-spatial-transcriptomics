  info <- stat_categories[[category_name]]
  
  df <- merged_df |>
    dplyr::filter(
      ROIType == info$ROIType
    )
  
  if (!is.na(info$Class)) {
    
    df <- df |>
      dplyr::filter(
        Class == info$Class
      )
  }
  
  for (pathway in info$Pathways) {
    
    if (!pathway %in% colnames(df)) {
      
      stat_results[[result_index]] <- data.frame(
        Category = category_name,
        Pathway = pathway,
        ROIType = info$ROIType,
        RestrictedClass = info$Class,
        Comparison = info$CompareBy,
        P_value = NA_real_,
        stringsAsFactors = FALSE
      )
      
      result_index <- result_index + 1L
      next
    }
    
    p <- safe_wilcox(
      df[[pathway]],
      df[[info$CompareBy]]
